#!/usr/bin/env python3
"""Convert decoder/fill_tables.h (op lists from decoder/gen_fill.py, the symbolic execution of
the player's ARM fill routines) into src/fill_data.rs. The op lists describe code structure
(which bytes are averaged into which), not ROM data; both player builds use the same lists.

  tools/fill_to_rs.py ../../decoder/fill_tables.h > src/fill_data.rs
"""
import re
import sys

src = open(sys.argv[1]).read()
ops, index = [], []
for m in re.finditer(r"/\* (m4|pl|pc) (\d+)x(\d+): ARM (0x[0-9a-f]+), (\d+) ops \*/\s*static const vx_fillop \w+\[\] = \{(.*?)\};", src, re.S):
    name, w, h, addr, n, body = m.group(1), int(m.group(2)), int(m.group(3)), m.group(4), int(m.group(5)), m.group(6)
    rows = re.findall(r"\{(-?\d+),(-?\d+),(-?\d+),(-?\d+),(-?\d+),(-?\d+),(-?\d+)\}", body)
    assert len(rows) == n, (name, w, h)
    index.append((name, w, h, len(ops), n, addr))
    ops += rows
out = ["// GENERATED by tools/fill_to_rs.py from decoder/fill_tables.h -- do not edit.",
       "// Op lists of the player's bilinear (mode 4) and plane (intra mode 3) fill routines, derived",
       "// by symbolic execution of the ARM code (decoder/gen_fill.py). See fill.rs for the semantics.",
       "use crate::fill::FillOp;", "",
       "#[rustfmt::skip]",
       f"pub(crate) static OPS: [FillOp; {len(ops)}] = ["]
for p, k, ar, br, d, a, b in ops:
    out.append(f"    FillOp {{ plane: {p}, kind: {k}, aref: {ar}, bref: {br}, dst: {d}, a: {a}, b: {b} }},")
out.append("];")
out.append("")
out.append("/// (family 0 = mode 4, 1 = luma plane, 2 = chroma plane; w; h; first op; op count; ARM routine)")
out.append("#[rustfmt::skip]")
out.append(f"pub(crate) static INDEX: [(u8, u8, u8, u16, u16, u32); {len(index)}] = [")
fam = {"m4": 0, "pl": 1, "pc": 2}
for name, w, h, s, n, addr in index:
    out.append(f"    ({fam[name]}, {w}, {h}, {s}, {n}, {addr}),")
out.append("];")
print("\n".join(out))
