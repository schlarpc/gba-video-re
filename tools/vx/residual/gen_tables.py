#!/usr/bin/env python3
"""Emit the residual decoder's literal tables (C) from the player's RAM images."""
import struct, os
H = os.path.dirname(os.path.abspath(__file__))
d = open(os.path.join(H, '../../../reference/vx/player/ewram.bin'), 'rb').read()
iw = open(os.path.join(H, '../../../reference/vx/player/iwram.bin'), 'rb').read()
L = struct.unpack('<4096H', d[0x10e4:0x10e4 + 0x2000])
lm = d[0x30e4:0x3164]; rm = d[0x3164:0x31e4]; cbp = iw[0x5610:0x5650]
def arr(vals, fmt, per):
    return '\n'.join('    ' + ', '.join(fmt % v for v in vals[i:i + per]) + ','
                     for i in range(0, len(vals), per))
s = '/* ---- tables generated by residual/gen_tables.py from player/ewram.bin, iwram.bin ---- */\n'
s += '/* EWRAM 0x020010e4 (ROM 0x9ae4): coefficient VLC LUT, index = next 12 bits.\n * entry: bits0-3 len (incl. sign bit), 4-8 |level|, 9-14 run, 15 last. */\n'
s += 'const uint16_t vx_coef_lut[4096] = {\n' + arr(L, '0x%04x', 12) + '\n};\n\n'
s += '/* EWRAM 0x020030e4: escape mode 1 level offset LMAX[last*64 + run] (MPEG-4 intra LMAX) */\nstatic const uint8_t vx_coef_lmax[128] = {\n' + arr(lm, '%2d', 16) + '\n};\n\n'
s += '/* EWRAM 0x02003164: escape mode 2 run offset (RMAX+1)[last*64 + |level|] (MPEG-4 intra RMAX + 1) */\nstatic const uint8_t vx_coef_rmax[128] = {\n' + arr(rm, '%2d', 16) + '\n};\n\n'
s += '/* IWRAM 0x03005610: ue(v) -> CBP (bit0..3 luma 4x4 raster, bit4 U, bit5 V) */\nstatic const uint8_t vx_cbp_tab[64] = {\n' + arr(cbp, '0x%02x', 16) + '\n};\n'
print(s, end='')
