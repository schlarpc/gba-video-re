#!/usr/bin/env python3
"""Vector instructions the model faulted on during LLE runs -> $PLAYYAN_WORK/runs/VECTOR_FAULTS.txt
(none on the shipped firmware images).  Each run saves runs/vfaults/<tag>.json; this merges them,
sorted by count.  Function names come from $PLAYYAN_WORK/lst/<image>.reach.lst when present
(vc01dis2.py IMG > that file).
  vfreport.py            rebuild VECTOR_FAULTS.txt from runs/vfaults/*.json"""
import collections
import glob
import json
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ISA = HERE
sys.path.append(os.path.join(HERE, '..'))
import workdir  # noqa: E402
OUT = workdir.work('runs')
WHY = {1: 'opcode not modelled', 2: 'condition not modelled', 3: 'memory B form (mform) not modelled',
       4: 'sru', 5: '8-bit vector memory access', 6: 'vec NOP mode'}
IMG = {'loader': 'py_fwldr', 'video': 'py_fw0', 'music': 'py_fw1'}
IMG_MICRO = {'loader': 'mi_fwldr', 'video': 'mi_fw0', 'music': 'mi_fw1'}


def save(tag, faults):
    d = os.path.join(OUT, 'vfaults')
    os.makedirs(d, exist_ok=True)
    json.dump(faults, open(os.path.join(d, '%s.json' % tag), 'w'))
    build()


def disasm(img, pc, words):
    try:
        sys.path.insert(0, ISA)
        import vc01
        w = list(words)
        i = vc01.decode(lambda a: w[(a - pc) // 2] if 0 <= (a - pc) // 2 < len(w) else 0, pc)
        return i.text()
    except Exception as e:  # noqa
        return '?'


def funcof(img, pc, cache={}):
    n = IMG.get(img, img)
    if n not in cache:
        p = os.path.join(workdir.WORK, 'lst', '%s.reach.lst' % n)
        fs = []
        if os.path.exists(p):
            for l in open(p):
                if l.startswith('; ===== function'):
                    fs.append(int(l.split()[-1], 16))
        cache[n] = sorted(fs)
    import bisect
    fs = cache[n]
    k = bisect.bisect_right(fs, pc) - 1
    return fs[k] if k >= 0 else None


def build():
    agg = {}
    runs = collections.defaultdict(set)
    for p in sorted(glob.glob(os.path.join(OUT, 'vfaults', '*.json'))):
        tag = os.path.basename(p)[:-5]
        for f in json.load(open(p)):
            k = (f.get('image'), f['pc'])
            if k not in agg:
                agg[k] = dict(f, count=0)
            agg[k]['count'] += f['count']
            runs[k].add(tag)
    rows = sorted(agg.values(), key=lambda f: -f['count'])
    out = ['VC01 vector instructions the LLE emulator could not execute (tools/playyan/vc01)',
           '===============================================================================',
           'Generated by vc01/vfreport.py from $PLAYYAN_WORK/runs/vfaults/*.json (one file per run.py --lle run).',
           'count = executions skipped (the instruction ran as a NOP and the firmware continued).',
           'image: the image running when it was hit (loader / video py_fw0 / music py_fw1 / fup_sec0/1 /',
           'mi_*).  why: what the C port of vc01v.py lacks.  func: enclosing function from',
           '$PLAYYAN_WORK/lst/<img>.reach.lst.  Sorted by count; same encoding at another pc = another row.',
           '',
           'GATING (not ranked by count because the video run stops early): py_fw0 0x01FEA0, the MPEG-4',
           'bitstream unpacker (op24 #1..#15 + vlsr, mform-2 vld/vst).  Without it the start-code search',
           '0x250E never ends, so VIDEO_INFO (thumbnails, Garage hashes) and all video playback are blocked.',
           'The same routine exists in mi_fw0 (0x0344C0) and fup_sec0.',
           '',
           '%-8s %-9s %-8s %-11s %-30s %-35s %s' % ('count', 'image', 'pc', 'func', 'encoding', 'why', 'disassembly (vc01v)')]
    for f in rows:
        fn = funcof(f.get('image'), f['pc'])
        out.append('%-8d %-9s %06x   %-11s %-30s %-35s %s' % (
            f['count'], f.get('image'), f['pc'], ('%06x' % fn) if fn is not None else '?',
            ' '.join('%04x' % w for w in f['words']), WHY.get(f['why'], f['why']),
            disasm(f.get('image'), f['pc'], f['words'])))
    # summary by opcode / reason
    by = collections.Counter()
    for f in rows:
        h0 = f['words'][0]
        key = ('op%d' % ((h0 >> 3) & 63), '48' if (h0 >> 9) & 1 else '80', WHY.get(f['why'], f['why']))
        by[key] += f['count']
    # function-level priority list (put first: it is what to work on)
    byf = collections.Counter(); fops = collections.defaultdict(collections.Counter)
    for f in rows:
        fn = funcof(f.get('image'), f['pc'])
        k = (f.get('image'), fn)
        byf[k] += f['count']
        fops[k]['op%d' % ((f['words'][0] >> 3) & 63)] += f['count']
    head = ['', 'PRIORITY BY FUNCTION (sum of counts over its faulting instructions; top 40):']
    for (img, fn), v in byf.most_common(40):
        head.append('  %-11d %-9s %-8s %s' % (v, img, ('%06x' % fn) if fn is not None else '?',
                                            ' '.join('%s:%d' % kv for kv in fops[(img, fn)].most_common(6))))
    head.append('')
    out[8:8] = head
    out += ['', 'By opcode / reason (sum of counts):']
    for k, v in by.most_common():
        out.append('  %-8d %s %s-bit: %s' % (v, k[0], k[1], k[2]))
    open(os.path.join(OUT, 'VECTOR_FAULTS.txt'), 'w').write('\n'.join(out) + '\n')
    return rows


if __name__ == '__main__':
    r = build()
    print('%d distinct faults' % len(r))
