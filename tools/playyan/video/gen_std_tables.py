#!/usr/bin/env python3
"""Emit the ISO 14496-2 / H.263 standard VLC and scan tables (published standard tables, allowed to be
embedded) as Rust (crates/gbav-playyan/src/m4v_tables.rs) and C (reference/playyan/video/m4v_tables.h).
Source: FFmpeg's transcription of the standard (FFMPEG_SRC = its libavcodec directory)."""
import os, re, sys
WORK = os.environ.get('PLAYYAN_WORK') or os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'tmp', 'playyan')  # tools/playyan/workdir.py
SRC = os.environ.get('FFMPEG_SRC', '')  # an FFmpeg libavcodec directory
D = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')

def carr(fname, name):
    t = open(os.path.join(SRC, fname)).read()
    m = re.search(re.escape(name) + r'\s*(\[[^\]]*\])+\s*=\s*\{(.*?)\};', t, re.S)
    body = re.sub(r'//[^\n]*', '', m.group(2))
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    return [int(x, 0) for x in re.findall(r'-?0x[0-9a-fA-F]+|-?\d+', body)]

T = {}
T['INTRA_MCBPC'] = ('u8', 2, list(sum(zip(carr('h263data.c', 'ff_h263_intra_MCBPC_code'), carr('h263data.c', 'ff_h263_intra_MCBPC_bits')), ())))
T['INTER_MCBPC'] = ('u8', 2, list(sum(zip(carr('h263data.c', 'ff_h263_inter_MCBPC_code'), carr('h263data.c', 'ff_h263_inter_MCBPC_bits')), ())))
T['CBPY'] = ('u8', 2, carr('h263data.c', 'ff_h263_cbpy_tab'))
T['MVTAB'] = ('u8', 2, carr('h263data.c', 'ff_mvtab'))
T['INTER_VLC'] = ('u16', 2, carr('h263data.c', 'ff_inter_vlc'))
T['INTER_RUN'] = ('u8', 1, carr('h263data.c', 'ff_inter_run'))
T['INTER_LEVEL'] = ('u8', 1, carr('h263data.c', 'ff_inter_level'))
T['INTRA_VLC'] = ('u16', 2, carr('mpeg4data.h', 'ff_mpeg4_intra_vlc'))
T['INTRA_RUN'] = ('u8', 1, carr('mpeg4data.h', 'ff_mpeg4_intra_run'))
T['INTRA_LEVEL'] = ('u8', 1, carr('mpeg4data.h', 'ff_mpeg4_intra_level'))
T['DC_LUM'] = ('u8', 2, carr('mpeg4data.h', 'ff_mpeg4_DCtab_lum'))
T['DC_CHROM'] = ('u8', 2, carr('mpeg4data.h', 'ff_mpeg4_DCtab_chrom'))
T['ZIGZAG'] = ('u8', 1, carr('mathtables.c', 'ff_zigzag_direct'))
T['ALT_HORIZ'] = ('u8', 1, carr('mpegvideodata.c', 'ff_alternate_horizontal_scan'))
T['ALT_VERT'] = ('u8', 1, carr('mpegvideodata.c', 'ff_alternate_vertical_scan'))
T['Y_DC_SCALE'] = ('u8', 1, carr('mpeg4data.h', 'ff_mpeg4_y_dc_scale_table'))
T['C_DC_SCALE'] = ('u8', 1, carr('mpeg4data.h', 'ff_mpeg4_c_dc_scale_table'))
T['DC_THRESHOLD'] = ('u8', 1, carr('mpeg4data.h', 'ff_mpeg4_dc_threshold'))
T['DEFAULT_INTRA_MATRIX'] = ('u8', 1, carr('mpeg4data.h', 'ff_mpeg4_default_intra_matrix'))
T['DEFAULT_INTER_MATRIX'] = ('u8', 1, carr('mpeg4data.h', 'ff_mpeg4_default_non_intra_matrix'))
for k, (t, w, v) in T.items():
    assert len(v) % w == 0, k

hdr = 'ISO/IEC 14496-2 (MPEG-4 Part 2) and ITU-T H.263 standard tables, generated by tools/playyan/video/gen_std_tables.py'
rs = ['//! ' + hdr + '.', '//! VLC tables are (code, length) pairs; RL tables index runs/levels by VLC index.', '']
c = ['/* ' + hdr + ' */', '#pragma once', '#include <stdint.h>', '']
for k, (t, w, v) in T.items():
    n = len(v) // w
    if w == 1:
        rs.append('pub const %s: [%s; %d] = %s;' % (k, t, n, '[' + ', '.join(map(str, v)) + ']'))
        c.append('static const %s_t %s[%d] = {%s};' % (t.replace('u', 'uint'), k, n, ', '.join(map(str, v))))
    else:
        rows = ', '.join('(%d, %d)' % tuple(v[i:i + 2]) for i in range(0, len(v), 2))
        rs.append('pub const %s: [(%s, %s); %d] = [%s];' % (k, t, t, n, rows))
        rows = ', '.join('{%d, %d}' % tuple(v[i:i + 2]) for i in range(0, len(v), 2))
        c.append('static const %s_t %s[%d][2] = {%s};' % (t.replace('u', 'uint'), k, n, rows))
open(os.path.join(D, 'crates/gbav-playyan/src/m4v_tables.rs'), 'w').write('\n'.join(rs) + '\n')
os.makedirs(os.path.join(D, 'reference/playyan/video'), exist_ok=True)
open(os.path.join(D, 'reference/playyan/video/m4v_tables.h'), 'w').write('\n'.join(c) + '\n')
print({k: len(v[2]) // v[1] for k, v in T.items()})
