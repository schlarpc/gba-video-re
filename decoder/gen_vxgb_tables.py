#!/usr/bin/env python3
"""Generate vxgb_tables.h from a VXGB (GBA Video Rev 5) cartridge ROM.

The Rev 5 player (Shark Tale, Shrek 2: byte-identical player code) codes residuals with the
H.264 CAVLC code tables. This script copies the tables the player's ARM decoder uses, in the
player's own layout, so that the C decoder walks them exactly as the ARM does (including what
an invalid code decodes to):

  IWRAM 0x03005e90  u8 CBP[32]                 ue(v) -> cbp (bit0..3 luma 4x4, bit4 = U and V)
  IWRAM 0x03006120  u8 ct_node[8], ct_len[8]   coeff_token: start node / length-table offset per nC 0..7
  IWRAM 0x03006130  u8 [3][68]                 coeff_token code lengths, index = T1 | TC<<2
  IWRAM 0x030079c0  s8 tree[49][16]            coeff_token 4-bit-nibble tree (<0: next node -v, else symbol)
  IWRAM 0x03006200  u8 tz_width[15]            total_zeros peek width per TotalCoeff 1..15
  IWRAM 0x03006210  u32 tz_ptr[15]             -> u8 len[16] + u8 lut[1 << width]
  IWRAM 0x03006250  u8 rb_width[6]             run_before peek width per zerosLeft 1..6
  IWRAM 0x03006258  u32 rb_ptr[6]              -> u8 len[16] + u8 lut[1 << width]
  IWRAM 0x03006080  u32 level_thr[6]           suffixLength increment thresholds
  EWRAM 0x02002a14  u8 deq[6][8]               dequant scales per QP%6, index (y&1)*4 + x
plus the runtime IWRAM bytes 0x03000000..0x030003ff (the blitter's clamp table and the code
around it, with player_run's patches for a 240x160 movie), which differ from VX++ Shrek in
one byte (a literal-pool offset at 0x380 that the table index range reaches).

Usage: gen_vxgb_tables.py ROM > vxgb_tables.h
       gen_vxgb_tables.py --stub > vxgb_tables.h   (no VXGB ROM: builds a VX++-only decoder)
"""
import hashlib
import struct
import sys

EW_ROM, IW_ROM = 0x8A00, 0xB548
PATCHES = {0x10: 0x00, 0x11: 0x01, 0x18: 0x2C, 0x19: 0x01, 0x38C: 160, 0x394: 240}
# sha1 of the IWRAM image + EWRAM image of the Rev 5 player, to catch a wrong ROM
EXPECTED_SHA1 = "e24ef2ea2cbc2c9fc6a6f370dee6ead37e35486e"

if sys.argv[1] == "--stub":
    print("/* GENERATED by gen_vxgb_tables.py --stub: no VXGB ROM, VXGB decoding disabled. */")
    print("#ifndef VXGB_TABLES_H\n#define VXGB_TABLES_H\n#include <stdint.h>\n#define VXGB_HAVE_TABLES 0")
    for decl in ("uint8_t vxgb_cbp[32]", "uint8_t vxgb_ct_node[8]", "uint8_t vxgb_ct_lenoff[8]",
                 "uint8_t vxgb_ct_len[204]", "int8_t vxgb_ct_tree[784]", "uint8_t vxgb_tz_width[15]",
                 "uint8_t vxgb_rb_width[6]", "uint8_t *const vxgb_tz_tab[15]", "uint8_t *const vxgb_rb_tab[6]",
                 "uint32_t vxgb_level_thr[6]", "uint8_t vxgb_deq[48]", "uint8_t vxgb_iwram_lo[0x400]"):
        print(f"static const {decl};")
    print("#endif")
    sys.exit(0)
rom = open(sys.argv[1], "rb").read()
if rom[0x20200:0x20204] != b"VXGB":
    sys.exit("not a VXGB cartridge (no 'VXGB' at 0x20200)")
iw = rom[IW_ROM:IW_ROM + 0x7CD0]
ew = rom[EW_ROM:EW_ROM + 0x2B48]
digest = hashlib.sha1(iw + ew).hexdigest()
if EXPECTED_SHA1 and digest != EXPECTED_SHA1:
    sys.exit(f"unexpected player image (sha1 {digest}); not a Rev 5 VXGB player?")


def I(a, n):
    return iw[a - 0x03000000:a - 0x03000000 + n]


def w32(a):
    return struct.unpack_from("<I", iw, a - 0x03000000)[0]


def carr(name, ctype, data, per=16, fmt="0x{:02x}"):
    out = [f"static const {ctype} {name}[{len(data)}] = {{"]
    for i in range(0, len(data), per):
        out.append("  " + ", ".join(fmt.format(x) for x in data[i:i + per]) + ",")
    out.append("};")
    return out


out = ["/* GENERATED by gen_vxgb_tables.py from a VXGB ROM -- do not edit or commit. */",
       "#ifndef VXGB_TABLES_H", "#define VXGB_TABLES_H", "#include <stdint.h>", "#define VXGB_HAVE_TABLES 1"]
out += carr("vxgb_cbp", "uint8_t", I(0x03005E90, 32))
out += carr("vxgb_ct_node", "uint8_t", I(0x03006120, 8))
# length tables addressed as ct_len_base + ct_len[nC] - 16 from 0x03006130
lens = I(0x03006130, 3 * 68)
out += carr("vxgb_ct_lenoff", "uint8_t", [x - 16 for x in I(0x03006128, 8)])
out += carr("vxgb_ct_len", "uint8_t", lens)
tree = [x - 256 if x > 127 else x for x in I(0x030079C0, 49 * 16)]
out += carr("vxgb_ct_tree", "int8_t", tree, fmt="{:d}")
tzw = list(I(0x03006200, 15))
rbw = list(I(0x03006250, 6))
out += carr("vxgb_tz_width", "uint8_t", tzw)
out += carr("vxgb_rb_width", "uint8_t", rbw)
for nm, wid, ptr in (("tz", tzw, 0x03006210), ("rb", rbw, 0x03006258)):
    names = []
    for k, wd in enumerate(wid):
        t = w32(ptr + 4 * k)
        out += carr(f"vxgb_{nm}{k + 1}", "uint8_t", I(t, 16 + (1 << wd)))
        names.append(f"vxgb_{nm}{k + 1}")
    out.append(f"static const uint8_t *const vxgb_{nm}_tab[{len(wid)}] = {{ {', '.join(names)} }};")
out += carr("vxgb_level_thr", "uint32_t", struct.unpack_from("<6I", iw, 0x6080), per=6, fmt="0x{:x}")
out += carr("vxgb_deq", "uint8_t", ew[0x2A14:0x2A14 + 48], per=8)
lo = bytearray(iw[:0x400])
for off, val in PATCHES.items():
    lo[off] = val
out += carr("vxgb_iwram_lo", "uint8_t", lo)
out.append("#endif")
print("\n".join(out))
