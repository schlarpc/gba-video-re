#!/usr/bin/env python3
"""Generate fill_tables.h: exact op lists for the player's bilinear/"plane" fill routines,
obtained by symbolically executing the straight-line ARM (symfill.py).

Op semantics (executed in order):
  kind 0 AVG   : val[i] = (A + B) >> 1               (arithmetic shift)
  kind 1 CORNER: val[i] = ((A + B + 1) >> 1) + 2*se(v) (reads one se(v) from the bitstream)
  then         : plane[dst] = val[i] & 0xff
Operand: if ref flag set -> val[k] (the untruncated register value of an earlier op k),
         else            -> the byte currently in memory at offset (same plane; for an op whose
                            plane is 'C', offsets are byte offsets in the interleaved UV plane).
         Operand 'V' (only in the intra plane-mode inner fills) = the caller's corner value.
"""
import os
import sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from symfill import Sym, fmt  # noqa: E402

MODE4 = {  # block size -> mode-4 handler body (after the push/bl in the dispatch table)
    (16, 16): 0x3001ac0, (16, 8): 0x3001e98, (8, 16): 0x3002e08, (8, 8): 0x3003298,
    (16, 4): 0x300233c, (8, 4): 0x30036a8, (4, 16): 0x300405c, (4, 8): 0x30042f8, (4, 4): 0x30045e0,
    (16, 2): 0x3002564, (8, 2): 0x30039b0, (4, 2): 0x3004824,
    (2, 16): 0x3004c48, (2, 8): 0x3005168, (2, 4): 0x3005368, (2, 2): 0x30054d0,
}
# intra16 plane mode inner fills: tables 0x03000b78 (luma) / 0x03000e18 (chroma), index (w>>3)+(h>>3)*4
import struct
ROM = open(os.path.join(HERE, "..", "shrek.gba"), "rb").read()


def iw32(a):
    return struct.unpack_from("<I", ROM, a - 0x03000000 + 0xbcc8)[0]


PLANE_L, PLANE_C = {}, {}
for w in (4, 8, 16):
    for h in (4, 8, 16):
        idx = (w >> 3) + (h >> 3) * 4
        PLANE_L[(w, h)] = iw32(0x03000b78 + 4 * idx)
        PLANE_C[(w, h)] = iw32(0x03000e18 + 4 * idx)


def lower(stores, plane0=None):
    """Convert symbolic stores to op tuples (plane, dst, kind, a, aref, b, bref)."""
    ops = []
    idmap = {}

    def operand(e):
        if e[0] == 'M':
            return (e[2], 0)
        if e[0] == 'S':
            return (stores[e[1]][1], 0)  # memory read of a stored (truncated) byte
        if e[0] == 'V':
            return (0, 2)
        k = idmap.get(id(e))
        if k is None:
            for j, (_, _, v) in enumerate(stores):
                if v == e:
                    k = j
                    break
        if k is None:
            raise ValueError("operand not a previous op: " + fmt(e))
        return (k, 1)

    for i, (p, off, v) in enumerate(stores):
        p = p or plane0
        # CORNER: ((M + M + 1) >> 1) + (SE << 1)
        if v[0] == '+' and v[2][0] == '<<' and v[2][1][0] == 'SE':
            avg = v[1]
            assert avg[0] == '>>' and avg[2] == 1 and avg[1][0] == '+' and avg[1][2] == ('c', 1), fmt(v)
            s = avg[1][1]
            assert s[0] == '+', fmt(v)
            a, b = operand(s[1]), operand(s[2])
            assert a[1] == 0 and b[1] == 0
            ops.append((p, off, 1, a[0], a[1], b[0], b[1]))
        elif v[0] == '>>' and v[2] == 1 and v[1][0] == '+':
            a, b = operand(v[1][1]), operand(v[1][2])
            ops.append((p, off, 0, a[0], a[1], b[0], b[1]))
        elif v[0] == 'V' or v[0] == 'R':
            ops.append((p, off, 0, 0, 2, 0, 2))  # store of V itself: (V+V)>>1 == V
        else:
            raise ValueError(f"store {i}: {fmt(v)}")
        idmap[id(v)] = i
    return ops


def trace_inner(addr, plane):
    s = Sym()
    s.r4 = 0
    s.plane = plane
    s.regs['r6'] = ('V',)
    s.run(addr)
    return s.stores


def emit():
    out = ["/* GENERATED by gen_fill.py from the player's ARM code -- do not edit. */",
           "/* op: plane(0=Y,1=UV), dst offset, kind(0=avg,1=corner+se), a, aref, b, bref */",
           "/*   aref/bref: 0 = memory byte at offset, 1 = untruncated value of op #, 2 = V */",
           "#include <stdint.h>",
           "typedef struct { uint8_t plane, kind, aref, bref; int16_t dst, a, b; } vx_fillop;"]
    index = []
    for name, tab in (("m4", MODE4), ("pl", PLANE_L), ("pc", PLANE_C)):
        for (w, h), addr in sorted(tab.items()):
            if name == "m4":
                st = Sym(); st.r4 = 0; st.run(addr); stores = st.stores; ops = lower(stores)
            else:
                stores = trace_inner(addr, 'Y' if name == 'pl' else 'C')
                ops = lower(stores)
            cname = f"fill_{name}_{w}x{h}"
            out.append(f"/* {name} {w}x{h}: ARM 0x{addr:08x}, {len(ops)} ops */")
            out.append(f"static const vx_fillop {cname}[] = {{")
            for p, d, k, a, ar, b, br in ops:
                out.append(f"  {{{0 if p == 'Y' else 1},{k},{ar},{br},{d},{a},{b}}},")
            out.append("};")
            index.append((name, w, h, cname, len(ops)))
    for name in ("m4", "pl", "pc"):
        out.append(f"static const vx_fillop *const fill_{name}[17][17] = {{")
        for (n, w, h, c, l) in index:
            if n == name:
                out.append(f"  [{w}][{h}] = {c},")
        out.append("};")
        out.append(f"static const uint16_t fill_{name}_n[17][17] = {{")
        for (n, w, h, c, l) in index:
            if n == name:
                out.append(f"  [{w}][{h}] = {l},")
        out.append("};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    open(os.path.join(HERE, "fill_tables.h"), "w").write(emit())
    print("wrote fill_tables.h")
