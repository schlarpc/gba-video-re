#!/usr/bin/env python3
"""Generate iwram_lut.h from the cartridge ROM.

The YUV->RGB clamp table lives at IWRAM 0x030001f0 and is indexed from -260 to +509, so it
reads into the IRQ table and the blitter's own code. The decoder therefore needs the player's
runtime IWRAM 0x03000000..0x030003ff, which is the IWRAM image at ROM 0xbcc8 with the patches
player_run applies at startup (IRQ table entries, and the width/height immediates of the
self-modifying blitter for a 240x160 movie at brightness 0).

Usage: gen_iwram_lut.py ROM > iwram_lut.h
"""
import hashlib
import sys

IWRAM_ROM_OFFSET = 0xBCC8
PATCHES = {0x10: 0x00, 0x11: 0x01, 0x18: 0x2C, 0x19: 0x01, 0x38C: 160, 0x394: 240}
# sha1 of the patched 1 KiB, to catch a wrong ROM revision
EXPECTED_SHA1 = "6b04a46698c3441875ecde7213dc0b2fb5debe8c"

rom = open(sys.argv[1], "rb").read()
b = bytearray(rom[IWRAM_ROM_OFFSET:IWRAM_ROM_OFFSET + 0x400])
for off, val in PATCHES.items():
    b[off] = val
digest = hashlib.sha1(b).hexdigest()
if EXPECTED_SHA1 and digest != EXPECTED_SHA1:
    sys.exit(f"unexpected IWRAM image (sha1 {digest}); wrong ROM?")
out = ["/* GENERATED by gen_iwram_lut.py from the ROM -- do not edit or commit. */",
       "static const uint8_t vx_iwram_lo[0x400] = {"]
for i in range(0, 0x400, 16):
    out.append("  " + ", ".join(f"0x{x:02x}" for x in b[i:i + 16]) + ",")
out.append("};")
print("\n".join(out))
