#!/usr/bin/env python3
"""Generate iwram_lut.h from the cartridge ROM.

The YUV->RGB clamp table lives at IWRAM 0x030001f0 and is indexed from -260 to +509, so it
reads into the IRQ table and the blitter's own code. The decoder therefore needs the player's
runtime IWRAM 0x03000000..0x030003ff: the IWRAM image (its ROM offset comes from the player's
load header, see container/vxcart.py) with the IRQ table entries main() installs. The
blitter's height/width immediates (0x38c/0x394), which player_run patches per stream, are
left at the image's placeholder value here; vx_yuv_to_bgr555() patches them for the stream
it converts.

Usage: gen_iwram_lut.py [--force] ROM > iwram_lut.h
"""
import hashlib
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "container"))
import vxcart  # noqa: E402

PATCHES = {0x10: 0x00, 0x11: 0x01, 0x18: 0x2C, 0x19: 0x01}
# sha1 of the patched 1 KiB for each known player build, to catch an unknown player
KNOWN_SHA1 = {
    "0c325baac83cdb564030d26a78f3a51e5703e9a0": "VX++ player (Shrek, Shark Tale, Shrek 2 Rev 6; Shrek + Shark Tale Rev 5)",
}

args = [a for a in sys.argv[1:] if a != "--force"]
rom = open(args[0], "rb").read()
off = vxcart.player_layout(rom)["iwram"][0]
b = bytearray(rom[off:off + 0x400])
for o, val in PATCHES.items():
    b[o] = val
digest = hashlib.sha1(b).hexdigest()
if digest not in KNOWN_SHA1 and "--force" not in sys.argv:
    sys.exit(f"unknown player IWRAM image at ROM 0x{off:x} (sha1 {digest}); "
             "the blitter may differ. Re-run with --force to use it anyway.")
out = ["/* GENERATED by gen_iwram_lut.py from the ROM -- do not edit or commit. */",
       f"/* IWRAM image at ROM 0x{off:x}; {KNOWN_SHA1.get(digest, 'UNKNOWN player build')} */",
       "static const uint8_t vx_iwram_lo[0x400] = {"]
for i in range(0, 0x400, 16):
    out.append("  " + ", ".join(f"0x{x:02x}" for x in b[i:i + 16]) + ",")
out.append("};")
print("\n".join(out))
