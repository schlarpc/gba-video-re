#!/usr/bin/env python3
"""Emit the ISO 14496-3 AAC Huffman codebooks (scalefactor + 11 spectral; standard tables, Table
4.A.1-4.A.12) as C (hcb.h, next to this script) and Rust (crates/gbav-playyan/src/aac/hcb.rs) from
an aactab.c that lists them as code/bit arrays (FFmpeg's libavcodec/aactab.c does).
Usage: gen_hcb.py path/to/aactab.c"""
import os, re, sys
src = open(sys.argv[1]).read()
here = os.path.dirname(os.path.abspath(__file__))
out_h = os.path.join(here, 'hcb.h')
out_rs = os.path.join(here, '..', '..', '..', 'crates', 'gbav-playyan', 'src', 'aac', 'hcb.rs')
def arr(name):
    m = re.search(r'%s\[\d*\]\s*=\s*\{(.*?)\};' % re.escape(name), src, re.S)
    body = re.sub(r'//.*|/\*.*?\*/', '', m.group(1), flags=re.S)
    return [int(x, 0) for x in re.findall(r'0x[0-9a-fA-F]+|\d+', body)]
tabs = [('sf', arr('ff_aac_scalefactor_code'), arr('ff_aac_scalefactor_bits'))]
for i in range(1, 12):
    tabs.append(('cb%d' % i, arr('codes%d' % i), arr('bits%d' % i)))
with open(out_h, 'w') as f:
    f.write('/* ISO/IEC 14496-3 AAC Huffman codebooks (standard tables). Generated by gen_hcb.py. */\n')
    f.write('#include <stdint.h>\n')
    for n, c, b in tabs:
        f.write('static const uint32_t HCB_%s_CODE[%d] = {%s};\n' % (n.upper(), len(c), ','.join(str(x) for x in c)))
        f.write('static const uint8_t HCB_%s_BITS[%d] = {%s};\n' % (n.upper(), len(b), ','.join(str(x) for x in b)))
with open(out_rs, 'w') as f:
    f.write('//! ISO/IEC 14496-3 AAC Huffman codebooks (standard tables, Tables 4.A.1-4.A.12).\n')
    f.write('//! Generated by reference/playyan/aac/gen_hcb.py.\n\n')
    for n, c, b in tabs:
        f.write('pub const %s_CODE: [u32; %d] = [%s];\n' % (n.upper(), len(c), ', '.join(str(x) for x in c)))
        f.write('pub const %s_BITS: [u8; %d] = [%s];\n' % (n.upper(), len(b), ', '.join(str(x) for x in b)))
print('ok', [(n, len(c)) for n, c, b in tabs])
