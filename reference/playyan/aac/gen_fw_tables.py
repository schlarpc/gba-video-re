#!/usr/bin/env python3
"""Extract the regions of the Play-Yan Micro / playan.fup video image that the AAC decoder reads
(tables, windows, twiddles, band tables, the PNS random seed) into fw_tables.h.

  gen_fw_tables.py --micro "Play-Yan Micro (Japan).gba" > fw_tables.h   (image A, mi_fw0)
  gen_fw_tables.py --fup playan.fup > fw_tables.h                        (section 0, fup_sec0)
  gen_fw_tables.py --image mi_fw0.bin > fw_tables.h                      (an extracted image)

The image is identified by its md5; only these hashes are in the source tree."""
import sys, hashlib, struct

IMAGES = {'09df03a96a904fb472ad733c03e33eb3': ('mi_fw0', 0), 'cdb23583f909d7920f4f37d6e9a91f2e': ('fup_sec0', 1)}
RANGES = [(0x4400, 0xc200), (0x43000, None)]


def lz77(src, p):
    assert src[p] == 0x10
    size = src[p + 1] | src[p + 2] << 8 | src[p + 3] << 16
    out = bytearray(); p += 4
    while len(out) < size:
        flags = src[p]; p += 1
        for bit in range(7, -1, -1):
            if len(out) >= size: break
            if not flags >> bit & 1:
                out.append(src[p]); p += 1
            else:
                n = (src[p] >> 4) + 3; dist = ((src[p] & 15) << 8 | src[p + 1]) + 1; p += 2
                for _ in range(n): out.append(out[-dist])
    return bytes(out)


def micro(rom):
    out = b''; p = 0x0E7898
    while True:
        ptr = struct.unpack_from('<I', rom, p)[0]
        if ptr == 0: return out
        out += lz77(rom, ptr - 0x0C000000); p += 4


def fup(f, section=0):
    e = 0x40 + 16 * section
    off, size = struct.unpack_from('<II', f, e)
    out = bytearray(); p = off
    while len(out) < size:
        out += f[p:p + min(0x200, size - len(out))]; p += 0x201
    return bytes(out)


def main():
    kind, path = sys.argv[1], sys.argv[2]
    data = open(path, 'rb').read()
    img = {'--micro': micro, '--fup': fup, '--image': lambda d: d}[kind](data)
    h = hashlib.md5(img).hexdigest()
    if h not in IMAGES:
        sys.exit('not a known AAC-capable video image (md5 %s)' % h)
    name, which = IMAGES[h]
    print('/* Generated by gen_fw_tables.py from %s: regions of %s read by pyaac.c. Do not commit. */' % (path.split('/')[-1], name))
    print('#define FW_WHICH %d\n#define FW_IMAGE_LEN 0x%x' % (which, len(img)))
    segs = []
    for a, b in RANGES:
        b = len(img) if b is None else b
        print('static const unsigned char FW_SEG_%x[%d] = {' % (a, b - a))
        chunk = img[a:b]
        for i in range(0, len(chunk), 32):
            print(','.join(str(x) for x in chunk[i:i + 32]) + ',')
        print('};')
        segs.append('{0x%x, %d, FW_SEG_%x}' % (a, b - a, a))
    print('static const struct { unsigned addr, len; const unsigned char* d; } FW_SEGS[] = {%s};' % ', '.join(segs))


main()
