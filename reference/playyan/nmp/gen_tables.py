#!/usr/bin/env python3
"""Generate nmp_tables.h from the user's Nintendo MP3 Player ROM: rebuild the DSP's data memory from
the C54x boot table (ROM 0x0A8F34) and the C runtime's cinit records (program 0x48C2), then dump the
decoder's table regions, each checked against its md5.  Nothing from the ROM is in this source."""
import sys, struct, hashlib
BOOT_OFF, BOOT_WORDS, CINIT = 0x0A8F34, 0xF730, 0x48C2
BOOT_MD5 = '38b484de6408453ceeacbb65c409d58b'
TABLES = [('dct', 0x9400, 204, 'dd02c862a67b4c43124a46d8fd52bab4'),
          ('aa', 0x94CC, 32, 'b025a43d8602c6830c93da69ee8716ad'),
          ('win_s', 0x94EC, 12, 'cc5204f9ffa59b1a6d76460098d8c893'),
          ('win_l', 0x94F8, 36, 'c8db18a164ff9d28df2fe12fc2e08400'),
          ('rq', 0xB182, 826, 'f98f852b0c34edd575469c0b74e9352a'),
          ('imdct18', 0xB4BC, 648, '1af9305d2a1cca310cade0597c5f2afc'),
          ('imdct6', 0xB744, 72, '289d7f02171e5123c304301f447c2dd5'),
          ('synth', 0xB78C, 1024, 'a7e1f96494446d38aac109ea2457e268'),
          ('src', 0xE013, 1495, '26ea593d71051ca179599d1c1f1c4929')]
def fold(a):
    if 0x8000 <= a <= 0xFFFF: return a | 0x10000
    if (a >> 16) in (1, 2, 3, 4) and (a & 0xFFFF) < 0x8000: return a & 0xFFFF
    return a
rom = open(sys.argv[1], 'rb').read()
bt = rom[BOOT_OFF:BOOT_OFF + 2 * BOOT_WORDS]
if hashlib.md5(bt).hexdigest() != BOOT_MD5: sys.exit('not the Nintendo MP3 Player ROM (boot table md5)')
w = struct.unpack('<%dH' % BOOT_WORDS, bt)
hpi = [0] * 0x40000; i = 5
while w[i]:
    n = w[i]; dest = w[i + 1] << 16 | w[i + 2]
    for k in range(n): hpi[fold(dest + k)] = w[i + 3 + k]
    i += 3 + n
p = CINIT
while hpi[p]:
    n = hpi[p]; dest = hpi[p + 1]
    for k in range(n):
        a = (dest + k) & 0xFFFF; hpi[a if a < 0x8000 else 0x10000 | a] = hpi[p + 2 + k]
    p += 2 + n
data = hpi[0:0x8000] + hpi[0x18000:0x20000]
out = ['/* generated by gen_tables.py from your ROM; do not distribute */', '#include <stdint.h>']
for name, a, n, h in TABLES:
    ws = data[a:a + n]
    if hashlib.md5(struct.pack('<%dH' % n, *ws)).hexdigest() != h: sys.exit('table %s md5 mismatch' % name)
    out.append('#define NMP_%s_BASE 0x%04X' % (name.upper(), a))
    out.append('static const uint16_t nmp_%s[%d] = {' % (name, n))
    for k in range(0, n, 12): out.append('  ' + ', '.join('0x%04x' % v for v in ws[k:k + 12]) + ',')
    out.append('};')
print('\n'.join(out))
