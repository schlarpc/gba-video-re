#!/usr/bin/env python3
"""Build-time: extract the Play-Yan music firmware image from your ROM / playan.fup and write it
as a C header (fw_music.h). Accepts the Play-Yan ROM (fw1 raw at 0x5B258), the Play-Yan Micro
ROM (image B, LZ77 chunk list at 0xE7D34), playan.fup (section 1) or an extracted image.
Only md5s of the images are in this file.   usage: gen_fwimage.py FILE > fw_music.h"""
import sys, hashlib
IMAGES = {'904dbf90365f8ac1cdfb507f04d0a302': 0, '390ce952b1c269930628f2ca27ae3511': 1,
          '3951130fb9c128bf3035852b51e2a732': 2}

def lz77(src):
    assert src[0] == 0x10
    size = src[1] | src[2] << 8 | src[3] << 16
    out = bytearray(); p = 4
    while len(out) < size:
        flags = src[p]; p += 1
        for bit in range(7, -1, -1):
            if len(out) >= size: break
            if not flags >> bit & 1:
                out.append(src[p]); p += 1
            else:
                n = (src[p] >> 4) + 3; dd = ((src[p] & 15) << 8 | src[p + 1]) + 1; p += 2
                for _ in range(n): out.append(out[-dd])
    return bytes(out[:size])

def candidates(b):
    yield b[0x5B258:0x5B258 + 0x3F66C]
    try:
        out = bytearray(); p = 0xE7D34
        while True:
            ptr = int.from_bytes(b[p:p + 4], 'little')
            if not ptr: break
            out += lz77(b[ptr - 0x0C000000:]); p += 4
        yield bytes(out)
    except Exception:
        pass
    if b.startswith(b'Nintendo Playan firmware update program'):
        for e in range(b[0x3E]):
            ent = b[0x40 + 16 * e:0x50 + 16 * e]
            off = int.from_bytes(ent[0:4], 'little'); size = int.from_bytes(ent[4:8], 'little')
            out = bytearray(); p = off
            while len(out) < size:
                out += b[p:p + min(0x200, size - len(out))]; p += 0x201
            yield bytes(out)
    yield b

def main():
    b = open(sys.argv[1], 'rb').read()
    for c in candidates(b):
        k = IMAGES.get(hashlib.md5(c).hexdigest())
        if k is not None:
            print('/* generated by gen_fwimage.py from %s -- do not commit */' % sys.argv[1].split('/')[-1])
            print('static const int PYMP3_FW_KIND = %d;' % k)
            print('static const unsigned char PYMP3_FW[%d] = {' % len(c))
            for i in range(0, len(c), 24):
                print(','.join(str(x) for x in c[i:i + 24]) + ',')
            print('};')
            return
    sys.exit('no Play-Yan music image found in ' + sys.argv[1])

main()
