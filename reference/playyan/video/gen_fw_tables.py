#!/usr/bin/env python3
"""Generate fw_tables.h (the video firmware's non-standard tables) from your Play-Yan ROM,
Play-Yan Micro ROM or playan.fup.  usage: gen_fw_tables.py FILE... > fw_tables.h"""
import os, struct, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'common'))
from fwimage import images, table

LOC = {  # image: (IDCT prescale 0x100 B, AC/DC reciprocal 0x80 B, thumbnail box reciprocal 0x44 B)
    'py_fw0': (0xf240, 0x2c61c, 0x2765c),
    'mi_fw0': (0x1bec0, 0x41df0, 0x3bcac),
    'fup_sec0': (0x1bec0, 0x42168, 0x3c0cc),
}
imgs = images(sys.argv[1:])
name = next((n for n in ('py_fw0', 'mi_fw0', 'fup_sec0') if n in imgs), None)
if not name:
    sys.exit('no Play-Yan video firmware image found in ' + ' '.join(sys.argv[1:]))
img = imgs[name]; a, b, c = LOC[name]
pre = struct.unpack('<128H', table(img, a, 256, '9b55e2afdb1e92ac7e0539c2825c8fa0'))
rec = struct.unpack('<64H', table(img, b, 128, '09e73bfc2bb7480d3e029a88375cc622'))
box = struct.unpack('<17I', table(img, c, 68, '73a110145f176e9aafd2a188c7507782'))
# the 64 bytes after each scan table (zigzag, alternate-horizontal, alternate-vertical): where the
# coefficient loop stores events past scan index 63
SCANS = {'py_fw0': (0x29a04, 0x29a7c, 0x29abc), 'mi_fw0': (0x3f164, 0x3f230, 0x3f270),
         'fup_sec0': (0x3f4dc, 0x3f5a8, 0x3f5e8)}[name]
ZZ_EXT = {'py_fw0': 'aaf404a8b77ea37ddc3f90edf920968a', 'mi_fw0': 'b54d9c4ec849b3ecb0164bf0c5c4b5d2',
          'fup_sec0': 'a3c2b9be093373ae65e3fdf38c82f966'}[name]
ISO = ('abbb1bdb75c4e2f75b5181b656e02c91', '8627f242de52551030960f18540647be', '5d27a7bac2e9f47d7e54affda59f6162')
EXT = (ZZ_EXT, '5d27a7bac2e9f47d7e54affda59f6162', 'f4317ffadf1d7feb9fb58cd4a403d2c3')
ext = []
for k in range(3):
    table(img, SCANS[k], 64, ISO[k])
    ext.append(table(img, SCANS[k] + 64, 64, EXT[k]))
f = lambda v: ', '.join(map(str, v))
print('/* generated by gen_fw_tables.py from %s -- do not commit */' % name)
print('#pragma once\n#include <stdint.h>')
print('#define PYV_FW_IMAGE "%s"' % name)
print('static const uint16_t PYV_IDCT_PRESCALE[128] = {%s};' % f(pre))
print('static const uint16_t PYV_RECIP[64] = {%s};' % f(rec))
print('static const uint32_t PYV_BOXRECIP[17] = {%s};' % f(box))
print('static const uint8_t PYV_SCAN_EXT[3][64] = {%s};' % ', '.join('{%s}' % f(e) for e in ext))
print('#define PYV_SPILL_PAST_HARMLESS %d /* verified on mi_fw0; py_fw0 untested */' % (name != 'py_fw0'))
