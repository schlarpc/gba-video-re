/* H.264 frame zigzag: scan index -> raster index (y*4+x) */
static const uint8_t vx_zigzag[16] = { 0, 1, 4, 8, 5, 2, 3, 6, 9, 12, 13, 10, 7, 11, 14, 15 };

static inline uint8_t clip8(int v) { return v < 0 ? 0 : v > 255 ? 255 : (uint8_t)v; }

/* one 4x4 block. plane 0 = luma (4 consecutive bytes/row), 1 = U (bytes 0,2,4,6),
 * 2 = V (bytes 1,3,5,7). dst stride VX_STRIDE. */
static int block4x4(vx_bits *bs, const vx_qscale *q, uint8_t *dst, int plane)
{
    int32_t c[32];          /* scan-order levels; 16..31 = harmless overflow (ARM temp buf) */
    int pos = 0, lastpos = -1, err = 0;
    const int step = plane ? 2 : 1, off = plane == 2 ? 1 : 0;

    memset(c, 0, sizeof c);
    for (;;) {
        uint32_t e, last, run;
        int32_t level;
        if ((bs->buf >> 25) == 3) {                  /* escape 0000011 */
            int b8 = (bs->buf >> 24) & 1;
            if (!b8) {                               /* mode 1: level += LMAX[last][run] */
                vx_skip(bs, 8);
                e = vx_coef_lut[bs->buf >> 20];
                run = (e >> 9) & 63; last = e >> 15;
                level = (int32_t)((e >> 4) & 31) + vx_coef_lmax[e >> 9];
                if ((bs->buf >> (32 - (e & 15))) & 1) level = -level;
                vx_skip(bs, e & 15);
            } else if (!((bs->buf >> 23) & 1)) {     /* mode 2: run += RMAX[last][level]+1 */
                vx_skip(bs, 9);
                e = vx_coef_lut[bs->buf >> 20];
                last = e >> 15;
                level = (e >> 4) & 31;
                run = ((e >> 9) & 63) + vx_coef_rmax[level + (last << 6)];
                if ((bs->buf >> (32 - (e & 15))) & 1) level = -level;
                vx_skip(bs, e & 15);
            } else {                                 /* mode 3: last(1) run(6) level(s12) */
                vx_skip(bs, 9);
                last = bs->buf >> 31;
                run = (bs->buf >> 25) & 63;
                vx_skip(bs, 7);
                level = (int32_t)bs->buf >> 20;
                vx_skip(bs, 12);
            }
        } else {
            e = vx_coef_lut[bs->buf >> 20];
            run = (e >> 9) & 63; last = e >> 15;
            level = (e >> 4) & 31;
            if ((bs->buf >> (32 - (e & 15))) & 1) level = -level;
            vx_skip(bs, e & 15);
        }
        pos += run;
        if (pos >= 32) {
            /* ARM would overwrite the dequant scales / jump table (0x03005770+). */
            return -1;
        }
        c[pos] = level;
        lastpos = pos;
        pos++;
        if (last) break;
    }
    if (pos > 16) err = 1;  /* overflow into the ARM temp buffer: harmless, but not valid */

    if (lastpos == 0) {
        /* DC-only fast path 0x03005990: dc = c0*s0 + 32, add dc>>6 to all 16 samples */
        int32_t dc = (int32_t)((uint32_t)c[0] * (uint32_t)q->scale[0] + 32u) >> 6;
        for (int y = 0; y < 4; y++)
            for (int x = 0; x < 4; x++) {
                uint8_t *p = dst + y * VX_STRIDE + x * step + off;
                *p = clip8(*p + dc);
            }
        return err;
    }

    {
        int32_t m[16], t[16];
        for (int i = 0; i < 16; i++) {
            int r = vx_zigzag[i];
            int s = ((r >> 2) & 1) + (r & 1);       /* 0: even/even, 1: mixed, 2: odd/odd */
            m[r] = (int32_t)((uint32_t)c[i] * (uint32_t)q->scale[s]);
        }
        for (int x = 0; x < 4; x++) {               /* vertical pass */
            int32_t r0 = m[x], r1 = m[4 + x], r2 = m[8 + x], r3 = m[12 + x];
            int32_t e0 = (int32_t)((uint32_t)r0 + (uint32_t)r2);
            int32_t e1 = (int32_t)((uint32_t)r0 - (uint32_t)r2);
            int32_t e2 = (int32_t)((uint32_t)(r1 >> 1) - (uint32_t)r3);
            int32_t e3 = (int32_t)((uint32_t)r1 + (uint32_t)(r3 >> 1));
            t[x]      = (int32_t)((uint32_t)e0 + (uint32_t)e3);
            t[4 + x]  = (int32_t)((uint32_t)e1 + (uint32_t)e2);
            t[8 + x]  = (int32_t)((uint32_t)e1 - (uint32_t)e2);
            t[12 + x] = (int32_t)((uint32_t)e0 - (uint32_t)e3);
        }
        for (int y = 0; y < 4; y++) {               /* horizontal pass, +32, >>6, add, clip */
            int32_t r0 = (int32_t)((uint32_t)t[4 * y] + 32u), r1 = t[4 * y + 1];
            int32_t r2 = t[4 * y + 2], r3 = t[4 * y + 3];
            int32_t e0 = (int32_t)((uint32_t)r0 + (uint32_t)r2);
            int32_t e1 = (int32_t)((uint32_t)r0 - (uint32_t)r2);
            int32_t e2 = (int32_t)((uint32_t)(r1 >> 1) - (uint32_t)r3);
            int32_t e3 = (int32_t)((uint32_t)r1 + (uint32_t)(r3 >> 1));
            int32_t o[4];
            o[0] = (int32_t)((uint32_t)e0 + (uint32_t)e3);
            o[1] = (int32_t)((uint32_t)e1 + (uint32_t)e2);
            o[2] = (int32_t)((uint32_t)e1 - (uint32_t)e2);
            o[3] = (int32_t)((uint32_t)e0 - (uint32_t)e3);
            for (int x = 0; x < 4; x++) {
                uint8_t *p = dst + y * VX_STRIDE + x * step + off;
                *p = clip8(*p + (o[x] >> 6));
            }
        }
    }
    return err;
}

int vx_residual(vx_bits *bs, const vx_qscale *q, uint8_t *Y, uint8_t *UV, int w, int h)
{
    int err = 0;
    for (int by = 0; by < h; by += 8) {
        for (int bx = 0; bx < w; bx += 8) {
            uint8_t *y = Y + by * VX_STRIDE + bx;
            uint8_t *uv = UV + (by >> 1) * VX_STRIDE + bx;
            uint32_t idx = vx_ue(bs);
            unsigned cbp;
            int r = 0;
            if (idx >= 64) return -2;   /* ARM would index past the table into code bytes */
            cbp = vx_cbp_tab[idx];
            if (cbp & 0x01) r |= block4x4(bs, q, y, 0);
            if (r < 0) return r;
            if (cbp & 0x02) r |= block4x4(bs, q, y + 4, 0);
            if (r < 0) return r;
            if (cbp & 0x04) r |= block4x4(bs, q, y + 4 * VX_STRIDE, 0);
            if (r < 0) return r;
            if (cbp & 0x08) r |= block4x4(bs, q, y + 4 * VX_STRIDE + 4, 0);
            if (r < 0) return r;
            if (cbp & 0x10) r |= block4x4(bs, q, uv, 1);
            if (r < 0) return r;
            if (cbp & 0x20) r |= block4x4(bs, q, uv, 2);
            if (r < 0) return r;
            err |= r;
        }
    }
    return err;
}
